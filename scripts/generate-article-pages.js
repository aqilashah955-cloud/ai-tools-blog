'use strict';
/* Generate baked static pages for published articles.
 *
 * Why this exists: article cards link to /articles/<slug>/, and Vercel must
 * serve those URLs from the filesystem alone — the vercel.json rewrite to
 * /article.html?slug=<slug> did not work in production (404), so pretty
 * URLs now resolve to a real file: articles/<slug>/index.html.
 *
 * The page is baked from article.html (same shell) with the article's full
 * content rendered into it using the site's own renderer from assets/app.js,
 * so it works with no JavaScript fetch at all. The container uses
 * id="article-static" (not "article-root") so the client-side loader in
 * app.js leaves the baked content alone.
 *
 * Run: node scripts/generate-article-pages.js
 * Run it whenever an article is published, edited, or unpublished. It also
 * removes baked pages for articles that are no longer published.
 */

const fs = require('fs');
const path = require('path');
const vm = require('vm');

const root = path.resolve(__dirname, '..');

// Load the site's own renderer (pure functions) from assets/app.js.
// Stub the DOM so the file's DOMContentLoaded wiring never runs here.
const appSrc = fs.readFileSync(path.join(root, 'assets', 'app.js'), 'utf8');
const sandbox = {
  document: {
    addEventListener: function () {},
    querySelectorAll: function () { return []; },
    querySelector: function () { return null; },
  },
  window: {},
  console: console,
};
vm.createContext(sandbox);
vm.runInContext(appSrc, sandbox);
const parseFrontMatter = sandbox.parseFrontMatter;
const parseMarkdown = sandbox.parseMarkdown;
const readingTime = sandbox.readingTime;
const formatDate = sandbox.formatDate;
const escapeHtml = sandbox.escapeHtml;

function mustReplace(str, search, replacement, label) {
  if (str.indexOf(search) === -1) {
    throw new Error('Template mismatch in article.html — expected to find: ' + label);
  }
  return str.split(search).join(replacement);
}

function buildPage(meta, bodyHtml, readingMins) {
  const template = fs.readFileSync(path.join(root, 'article.html'), 'utf8');
  const desc = meta.description || meta.excerpt || '';
  const title = meta.title || meta.slug;

  let page = template;
  page = mustReplace(page, '<title>Article — AI Tools Blog</title>',
    '<title>' + escapeHtml(title) + ' — AI Tools Blog</title>', 'article <title>');
  page = mustReplace(page, '<meta name="description" content="A practical tutorial from the AI Tools Blog.">',
    '<meta name="description" content="' + escapeHtml(desc) + '">', 'meta description');
  page = mustReplace(page, '<meta property="og:title" content="AI Tools Blog">',
    '<meta property="og:title" content="' + escapeHtml(title) + '">', 'og:title');
  page = mustReplace(page, '<meta property="og:description" content="A practical tutorial from the AI Tools Blog.">',
    '<meta property="og:description" content="' + escapeHtml(desc) + '">', 'og:description');
  // Root-relative URLs: this page lives one level deep, so relative
  // asset/nav links would resolve under /articles/<slug>/.
  page = mustReplace(page, '<link rel="stylesheet" href="assets/style.css">',
    '<link rel="stylesheet" href="/assets/style.css">', 'stylesheet link');
  page = mustReplace(page, '<script src="assets/app.js" defer></script>',
    '<script src="/assets/app.js" defer></script>', 'app.js script');
  page = mustReplace(page, '<script src="assets/firebase-forms.js" defer></script>',
    '<script src="/assets/firebase-forms.js" defer></script>', 'firebase-forms.js script');
  page = mustReplace(page, 'href="index.html"', 'href="/"', 'home links');
  page = mustReplace(page, 'href="blog.html"', 'href="/blog.html"', 'blog links');
  page = mustReplace(page, 'href="about.html"', 'href="/about.html"', 'about links');
  page = mustReplace(page, 'href="contact.html"', 'href="/contact.html"', 'contact links');

  // Same meta line + video link the client-side loader builds, baked in.
  const metaHtml = '<p class="post-meta"><a class="chip" href="/blog.html?category=' +
    encodeURIComponent(meta.category) + '">' + escapeHtml(meta.category) + '</a>' +
    '<span>' + escapeHtml(formatDate(meta.date)) + '</span><span>' + readingMins + ' min read</span></p>';
  const videoHtml = meta.video_url
    ? '\n<p><a class="video-link" href="' + escapeHtml(meta.video_url) + '">▶ Watch the video version on YouTube</a></p>'
    : '';
  const baked = '<article class="article wrap-narrow" id="article-static">\n' +
    metaHtml + '\n' + bodyHtml + videoHtml + '\n  </article>';
  if (!/<article class="article wrap-narrow" id="article-root">[\s\S]*?<\/article>/.test(page)) {
    throw new Error('Template mismatch in article.html — expected #article-root block');
  }
  page = page.replace(
    /<article class="article wrap-narrow" id="article-root">[\s\S]*?<\/article>/,
    baked
  );

  return '<!DOCTYPE html>\n<!-- Generated by scripts/generate-article-pages.js — do not edit by hand. Edit articles/' +
    meta.slug + '.md and re-run the generator. -->\n' + page.replace(/^<!DOCTYPE html>\n/, '');
}

function main() {
  const index = JSON.parse(fs.readFileSync(path.join(root, 'articles', 'index.json'), 'utf8'));
  const slugs = index.articles || [];
  const published = [];

  slugs.forEach(function (slug) {
    const mdPath = path.join(root, 'articles', slug + '.md');
    if (!fs.existsSync(mdPath)) {
      console.log('SKIP (no .md file): ' + slug);
      return;
    }
    const parsed = parseFrontMatter(fs.readFileSync(mdPath, 'utf8'));
    const meta = parsed.meta;
    meta.slug = meta.slug || slug;
    if ((meta.status || '').toLowerCase() !== 'published') {
      console.log('SKIP (not published): ' + slug);
      return;
    }
    const bodyHtml = parseMarkdown(parsed.body);
    const mins = readingTime(parsed.body);
    const outDir = path.join(root, 'articles', slug);
    fs.mkdirSync(outDir, { recursive: true });
    fs.writeFileSync(path.join(outDir, 'index.html'), buildPage(meta, bodyHtml, mins));
    published.push(slug);
    console.log('WROTE articles/' + slug + '/index.html (' + mins + ' min read)');
  });

  // Remove baked pages for articles that are no longer published, so an
  // unpublished article cannot stay reachable at its pretty URL.
  fs.readdirSync(path.join(root, 'articles'), { withFileTypes: true })
    .filter(function (e) { return e.isDirectory(); })
    .forEach(function (dir) {
      if (published.indexOf(dir.name) !== -1) return;
      const baked = path.join(root, 'articles', dir.name, 'index.html');
      if (fs.existsSync(baked)) {
        fs.unlinkSync(baked);
        console.log('REMOVED stale baked page: articles/' + dir.name + '/index.html');
        try { fs.rmdirSync(path.join(root, 'articles', dir.name)); } catch (e) { /* not empty */ }
      }
    });

  console.log('Done. Published: ' + (published.join(', ') || '(none)'));
}

main();
